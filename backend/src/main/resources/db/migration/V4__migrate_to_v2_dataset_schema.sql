DROP TABLE recipe_ingredient;
DROP TABLE recipe_step;
DROP TABLE recipe;
DROP TABLE user_ingredient;
DROP TABLE ingredient;

CREATE TABLE ingredient (
    ingredient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key VARCHAR(255) NOT NULL,
    canonical_name VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ingredient_key UNIQUE (key),
    CONSTRAINT uq_ingredient_canonical_name UNIQUE (canonical_name)
);

CREATE TABLE ingredient_variant (
    ingredient_variant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key VARCHAR(255) NOT NULL,
    ingredient_id BIGINT NOT NULL,
    name VARCHAR(255) NOT NULL,
    is_base BOOLEAN NOT NULL,
    CONSTRAINT uq_ingredient_variant_key UNIQUE (key),
    CONSTRAINT uq_ingredient_variant_ingredient_name UNIQUE (ingredient_id, name),
    CONSTRAINT fk_ingredient_variant_ingredient
        FOREIGN KEY (ingredient_id) REFERENCES ingredient (ingredient_id)
);

CREATE TABLE user_ingredient (
    user_ingredient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    ingredient_variant_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_user_ingredient_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_user_ingredient_variant
        FOREIGN KEY (ingredient_variant_id)
            REFERENCES ingredient_variant (ingredient_variant_id),
    CONSTRAINT uq_user_ingredient_user_variant
        UNIQUE (user_id, ingredient_variant_id)
);

CREATE TABLE ingredient_variant_relation (
    source_variant_id BIGINT NOT NULL,
    target_variant_id BIGINT NOT NULL,
    CONSTRAINT pk_ingredient_variant_relation
        PRIMARY KEY (source_variant_id, target_variant_id),
    CONSTRAINT ck_ingredient_variant_relation_not_self
        CHECK (source_variant_id <> target_variant_id),
    CONSTRAINT fk_ingredient_variant_relation_source
        FOREIGN KEY (source_variant_id)
            REFERENCES ingredient_variant (ingredient_variant_id),
    CONSTRAINT fk_ingredient_variant_relation_target
        FOREIGN KEY (target_variant_id)
            REFERENCES ingredient_variant (ingredient_variant_id)
);

CREATE TABLE recipe (
    recipe_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_key VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    status VARCHAR(50) NOT NULL,
    shorts_reference VARCHAR(2048) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_recipe_dataset_key UNIQUE (dataset_key)
);

CREATE TABLE recipe_ingredient (
    recipe_ingredient_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL,
    ingredient_variant_id BIGINT,
    display_name VARCHAR(255) NOT NULL,
    raw_text TEXT NOT NULL,
    amount VARCHAR(255),
    unit VARCHAR(255),
    display_order INTEGER NOT NULL,
    is_optional BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_recipe_ingredient_recipe
        FOREIGN KEY (recipe_id) REFERENCES recipe (recipe_id) ON DELETE CASCADE,
    CONSTRAINT fk_recipe_ingredient_variant
        FOREIGN KEY (ingredient_variant_id)
            REFERENCES ingredient_variant (ingredient_variant_id),
    CONSTRAINT uq_recipe_ingredient_recipe_display_order
        UNIQUE (recipe_id, display_order)
);

CREATE TABLE recipe_step (
    recipe_step_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL,
    step_order INTEGER NOT NULL,
    content TEXT NOT NULL,
    CONSTRAINT fk_recipe_step_recipe
        FOREIGN KEY (recipe_id) REFERENCES recipe (recipe_id) ON DELETE CASCADE,
    CONSTRAINT uq_recipe_step_recipe_step_order
        UNIQUE (recipe_id, step_order)
);

CREATE TABLE recipe_requirement (
    recipe_requirement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL,
    display_order INTEGER NOT NULL,
    CONSTRAINT fk_recipe_requirement_recipe
        FOREIGN KEY (recipe_id) REFERENCES recipe (recipe_id) ON DELETE CASCADE,
    CONSTRAINT uq_recipe_requirement_recipe_display_order
        UNIQUE (recipe_id, display_order)
);

CREATE TABLE recipe_requirement_option (
    recipe_requirement_option_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_requirement_id BIGINT NOT NULL,
    recipe_ingredient_id BIGINT NOT NULL,
    display_order INTEGER NOT NULL,
    CONSTRAINT fk_recipe_requirement_option_requirement
        FOREIGN KEY (recipe_requirement_id)
            REFERENCES recipe_requirement (recipe_requirement_id) ON DELETE CASCADE,
    CONSTRAINT fk_recipe_requirement_option_ingredient
        FOREIGN KEY (recipe_ingredient_id)
            REFERENCES recipe_ingredient (recipe_ingredient_id) ON DELETE CASCADE,
    CONSTRAINT uq_recipe_requirement_option_requirement_ingredient
        UNIQUE (recipe_requirement_id, recipe_ingredient_id),
    CONSTRAINT uq_recipe_requirement_option_requirement_display_order
        UNIQUE (recipe_requirement_id, display_order)
);

CREATE TABLE recipe_requirement_substitute (
    recipe_requirement_substitute_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_requirement_option_id BIGINT NOT NULL,
    recipe_ingredient_id BIGINT NOT NULL,
    display_order INTEGER NOT NULL,
    CONSTRAINT fk_recipe_requirement_substitute_option
        FOREIGN KEY (recipe_requirement_option_id)
            REFERENCES recipe_requirement_option (recipe_requirement_option_id)
            ON DELETE CASCADE,
    CONSTRAINT fk_recipe_requirement_substitute_ingredient
        FOREIGN KEY (recipe_ingredient_id)
            REFERENCES recipe_ingredient (recipe_ingredient_id) ON DELETE CASCADE,
    CONSTRAINT uq_recipe_requirement_substitute_option_ingredient
        UNIQUE (recipe_requirement_option_id, recipe_ingredient_id),
    CONSTRAINT uq_recipe_requirement_substitute_option_display_order
        UNIQUE (recipe_requirement_option_id, display_order)
);

CREATE TABLE recipe_requirement_allowed_variant (
    recipe_requirement_option_id BIGINT NOT NULL,
    ingredient_variant_id BIGINT NOT NULL,
    CONSTRAINT pk_recipe_requirement_allowed_variant
        PRIMARY KEY (recipe_requirement_option_id, ingredient_variant_id),
    CONSTRAINT fk_recipe_requirement_allowed_variant_option
        FOREIGN KEY (recipe_requirement_option_id)
            REFERENCES recipe_requirement_option (recipe_requirement_option_id)
            ON DELETE CASCADE,
    CONSTRAINT fk_recipe_requirement_allowed_variant_variant
        FOREIGN KEY (ingredient_variant_id)
            REFERENCES ingredient_variant (ingredient_variant_id)
);

CREATE INDEX idx_ingredient_variant_ingredient_id
    ON ingredient_variant (ingredient_id);
CREATE INDEX idx_recipe_ingredient_recipe_id
    ON recipe_ingredient (recipe_id);
CREATE INDEX idx_recipe_ingredient_variant_id
    ON recipe_ingredient (ingredient_variant_id);
CREATE INDEX idx_recipe_step_recipe_id
    ON recipe_step (recipe_id);
CREATE INDEX idx_recipe_requirement_recipe_id
    ON recipe_requirement (recipe_id);
CREATE INDEX idx_recipe_requirement_option_requirement_id
    ON recipe_requirement_option (recipe_requirement_id);
CREATE INDEX idx_recipe_requirement_substitute_option_id
    ON recipe_requirement_substitute (recipe_requirement_option_id);
